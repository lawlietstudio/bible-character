#!/usr/bin/env python3
"""Fetch the Biblica Open Chinese Contemporary Bible (聖經，當代譯本開放資源, Traditional script) — a readable, thought-for-thought
translation — and write data/<book>.ccb.js, one plain-text line per verse, next to the 和合本 / WEB text in data/<book>.text.js.

  Source : https://ebible.org/cmncbt/   (copyright © 1979, 2005, 2007, 2012, 2023 Biblica, Inc.)
  Licence: Creative Commons Attribution-ShareAlike 4.0 (CC BY-SA 4.0) — https://creativecommons.org/licenses/by-sa/4.0
           The notice that every output file carries is in HEADER below; keep it if you edit this script.

Usage:  python scripts/fetch_ccb.py obadiah        # one book
        python scripts/fetch_ccb.py --all          # every book in BOOKS below
Output: window.BIBLE_CCB["obadiah"] = { "1": { "1": "…", … }, … }

What the script changes (and says so in the header): it splits the text into verses and drops the section headings, footnote
marks and the line breaks of poetry. The words themselves are untouched. Verses are then compared with the 和合本 verse
list so numbering differences (merged or missing verses) are reported instead of silently shown against the wrong verse.
"""
from __future__ import annotations

import html
import json
import re
import sys
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://ebible.org/cmncbt/"
UA = {"User-Agent": "bible-character-site/0.1 (personal study project)"}
# our book id -> (ebible/USFM code, chapters)
BOOKS = {
    "ruth": ("RUT", 4),
    "jeremiah": ("JER", 52),
    "lamentations": ("LAM", 5),
    "ezekiel": ("EZK", 48),
    "daniel": ("DAN", 12),
    "hosea": ("HOS", 14),
    "joel": ("JOL", 3),
    "amos": ("AMO", 9),
    "obadiah": ("OBA", 1),
    "jonah": ("JON", 4),
}

HEADER = """\
// 聖經，當代譯本開放資源 (Open Chinese Contemporary Bible, Traditional Script) — {book}
// 版權所有 © 1979, 2005, 2007, 2012, 2023 Biblica, Inc.  Copyright © 1979, 2005, 2007, 2012, 2023 by Biblica, Inc.
// Licensed under the Creative Commons Attribution-ShareAlike 4.0 International License (CC BY-SA 4.0):
// https://creativecommons.org/licenses/by-sa/4.0 — this file is shared under the same licence.
// The original work by Biblica, Inc. is available for free at www.biblica.com and open.bible (source: https://ebible.org/cmncbt/).
// Changes made: the text was split into one line per verse; section headings, footnote marks and poetry line breaks were
// removed. The wording is unchanged. (Generated by scripts/fetch_ccb.py)
"""


def get(url: str) -> str:
    for attempt in range(4):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30) as r:
                return r.read().decode("utf-8", "replace")
        except Exception as e:  # noqa: BLE001
            print(f"  retry {attempt + 1} ({e})", file=sys.stderr)
            time.sleep(2 + attempt * 3)
    raise RuntimeError(f"failed: {url}")


def parse_chapter(page: str) -> dict[int, str]:
    """-> {verse number: text}. A bridged label such as '5-6' puts the text on verse 5 and records '（見上節）' on 6."""
    body = page[page.index('<div class="main"'):]
    body = body.split("<ul class='tnav'>")[0]
    body = re.sub(r'\s*<a href="#FN\d+" class="notemark">.*?</a>', "", body, flags=re.S)        # footnote marks + their popups
    body = re.sub(r"<div class='(?:mt|s|r|d|ms|mr|sp)'>.*?</div>", "", body, flags=re.S)        # titles, section headings
    body = re.sub(r"<div class='chapterlabel'[^>]*>.*?</div>", "", body, flags=re.S)
    body = re.sub(r"</?div[^>]*>", "\x01", body)                                                 # line / paragraph boundaries
    marks = list(re.finditer(r'<span class="verse" id="V(\d+)">([^<]*)</span>', body))
    out: dict[int, str] = {}
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(body)
        seg = re.sub(r"<[^>]+>", "", body[m.end():end])
        seg = html.unescape(seg).replace(" ", " ")
        seg = re.sub(r"\s*\x01\s*", "", seg)                                                     # join lines (no space in Chinese)
        seg = re.sub(r"\s+", " ", seg).strip()
        label = html.unescape(m.group(2)).replace(" ", "").strip()
        first = int(m.group(1))
        out[first] = seg
        rng = re.fullmatch(r"(\d+)[-–](\d+)", label)
        if rng:
            for k in range(int(rng.group(1)) + 1, int(rng.group(2)) + 1):
                out[k] = "（見上節）"
    return out


def cuv_keys(book: str) -> dict[str, list[int]]:
    t = (ROOT / "data" / f"{book}.text.js").read_text(encoding="utf-8")
    data = json.loads(t[t.index("= {") + 2:].rstrip().rstrip(";"))
    return {ch: sorted(int(v) for v in vs) for ch, vs in data.items()}


def fetch_book(book: str) -> None:
    code, chapters = BOOKS[book]
    ref = cuv_keys(book)
    out: dict[str, dict[str, str]] = {}
    problems: list[str] = []
    for ch in range(1, chapters + 1):
        page = get(f"{BASE}{code}{ch:02d}.htm")
        verses = parse_chapter(page)
        want = ref.get(str(ch), [])
        miss = [v for v in want if v not in verses]
        extra = [v for v in verses if v not in want]
        if miss:
            problems.append(f"{book} {ch}: 當代譯本 has no verse {miss}")
        if extra:
            problems.append(f"{book} {ch}: 當代譯本 has extra verse {extra} (not in 和合本)")
        empty = [v for v, s in verses.items() if not s]
        if empty:
            problems.append(f"{book} {ch}: empty text for verse {empty}")
        out[str(ch)] = {str(v): verses[v] for v in sorted(verses)}
        print(f"{book} {ch}: {len(verses)} verses", flush=True)
        time.sleep(0.4)
    target = ROOT / "data" / f"{book}.ccb.js"
    target.write_text(
        HEADER.format(book=book)
        + "window.BIBLE_CCB = window.BIBLE_CCB || {};\n"
        + f"window.BIBLE_CCB[{json.dumps(book)}] = {json.dumps(out, ensure_ascii=False, indent=1)};\n",
        encoding="utf-8",
    )
    total = sum(len(c) for c in out.values())
    print(f"wrote {target.name} — {len(out)} chapters, {total} verses; {len(problems)} numbering notes")
    for p in problems:
        print("  NOTE", p)


def main() -> None:
    args = sys.argv[1:]
    books = list(BOOKS) if args == ["--all"] else args
    if not books or any(b not in BOOKS for b in books):
        sys.exit(f"usage: fetch_ccb.py <{'|'.join(BOOKS)}> | --all")
    for b in books:
        fetch_book(b)


if __name__ == "__main__":
    main()
