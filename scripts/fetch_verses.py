#!/usr/bin/env python3
"""Fetch the full text of a book in two public-domain translations and write data/<book>.text.js.

  Chinese : 和合本 (CUV, Traditional)  via bible.fhl.net  (信望愛站)
  English : World English Bible (WEB)   via bible-api.com

Usage:  python scripts/fetch_verses.py            # Daniel (default)
Output: window.BIBLE_TEXT["daniel"] = { "1": { "1": {zh, en}, ... }, ... }
"""
from __future__ import annotations

import json
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOOKS = {
    # id: (FHL short Chinese name, bible-api slug, chapters)
    "daniel": ("但", "daniel", 12),
    "ruth": ("得", "ruth", 4),
    "jeremiah": ("耶", "jeremiah", 52),
    "lamentations": ("哀", "lamentations", 5),
    "ezekiel": ("結", "ezekiel", 48),
    "hosea": ("何", "hosea", 14),
    "joel": ("珥", "joel", 3),
    "amos": ("摩", "amos", 9),
    "obadiah": ("俄", "obadiah", 1),
    "jonah": ("拿", "jonah", 4),
    "micah": ("彌", "micah", 7),
    "nahum": ("鴻", "nahum", 3),
    "habakkuk": ("哈", "habakkuk", 3),
}
UA = {"User-Agent": "bible-character-site/0.1 (personal study project)"}


def get_json(url: str) -> dict:
    for attempt in range(4):
        try:
            req = urllib.request.Request(url, headers=UA)
            with urllib.request.urlopen(req, timeout=30) as r:
                return json.loads(r.read().decode("utf-8"))
        except Exception as e:  # noqa: BLE001
            print(f"  retry {attempt + 1} ({e})", file=sys.stderr)
            time.sleep(2 + attempt * 3)
    raise RuntimeError(f"failed: {url}")


def clean_zh(s: str) -> str:
    # FHL pads 神 / 主 etc. with ideographic spaces for typesetting; drop them.
    s = re.sub(r"[　 ]+", "", s).strip()
    # Where 和合本 runs two verses together, FHL leaves a one-letter placeholder ("a") in the second one
    # (Jer 34:9, 34:19, 43:6). Show an explicit, mutable note instead.
    return "（見上節）" if re.fullmatch(r"[a-z]", s) else s


def clean_en(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


def fetch_book(book: str) -> dict:
    zh_name, slug, chapters = BOOKS[book]
    out: dict[str, dict] = {}
    for ch in range(1, chapters + 1):
        print(f"{book} {ch} …", flush=True)
        zh = get_json(
            "https://bible.fhl.net/json/qb.php?"
            + urllib.parse.urlencode({"chineses": zh_name, "chap": ch, "version": "unv", "gb": 0})
        )
        # bible-api.com reads "obadiah 1" as *verse* 1 for one-chapter books, so ask for the verse range explicitly
        ref = f"{slug}+{ch}:1-{len(zh['record'])}" if chapters == 1 else f"{slug}+{ch}"
        en = get_json(f"https://bible-api.com/{ref}?translation=web")
        verses: dict[str, dict] = {}
        for rec in zh["record"]:
            verses[str(rec["sec"])] = {"zh": clean_zh(rec["bible_text"]), "en": ""}
        for v in en["verses"]:
            verses.setdefault(str(v["verse"]), {"zh": "", "en": ""})["en"] = clean_en(v["text"])
        missing = [k for k, v in verses.items() if not v["zh"] or not v["en"]]
        if missing:
            print(f"  WARNING chapter {ch}: incomplete verses {missing}", file=sys.stderr)
        out[str(ch)] = dict(sorted(verses.items(), key=lambda kv: int(kv[0])))
        time.sleep(2.5)  # bible-api.com is rate limited (15 req / 30 s)
    return out


def main() -> None:
    book = sys.argv[1] if len(sys.argv) > 1 else "daniel"
    data = fetch_book(book)
    total = sum(len(c) for c in data.values())
    target = ROOT / "data" / f"{book}.text.js"
    target.write_text(
        "// Generated by scripts/fetch_verses.py — 和合本 (CUV, public domain) + World English Bible (public domain)\n"
        "window.BIBLE_TEXT = window.BIBLE_TEXT || {};\n"
        f"window.BIBLE_TEXT[{json.dumps(book)}] = {json.dumps(data, ensure_ascii=False, indent=1)};\n",
        encoding="utf-8",
    )
    print(f"wrote {target} — {len(data)} chapters, {total} verses")


if __name__ == "__main__":
    main()
